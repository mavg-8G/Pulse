import { apiGet, apiPost, expect, expectAccessible, register, test } from './helpers'

test.use({ serviceWorkers: 'block' }) // Los fallos HTTP simulados deben pasar por las rutas de Playwright.

test('una lectura lenta no muestra cifras del mes anterior bajo el nuevo periodo', async ({ page }) => {
  await register(page)
  const account = (await apiGet(page, '/api/accounts'))[0]
  const category = (await apiGet(page, '/api/categories'))[0]
  const month = (await apiGet(page, '/api/dashboard')).month
  await apiPost(page, '/api/transactions', { account_id: account.id, category_id: category.id, amount_cents: 1300, occurred_at: `${month}-01T12:00`, merchant: 'Solo este mes' })
  await page.goto('/movimientos')
  await expect(page.getByText('Solo este mes', { exact: true })).toBeVisible()
  let release!: () => void
  let held = false
  const gate = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/api/transactions?**', async (route) => {
    if (new URL(route.request().url()).searchParams.get('month') === month) return route.continue()
    held = true
    await gate
    await route.continue()
  })
  await page.getByRole('button', { name: 'Mes anterior' }).click()
  await expect.poll(() => held).toBeTruthy()
  await expect(page.getByText('Solo este mes', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('status', { name: 'Cargando movimientos' })).toBeVisible()
  release()
  await expect(page.getByText(/Sin movimientos en/)).toBeVisible()
})

test('volver conserva filtros, filas, búsqueda privada y posición; Plan conserva su mes', async ({ page }) => {
  await register(page)
  const accounts = await apiGet(page, '/api/accounts')
  const cats = await apiGet(page, '/api/categories')
  const comida = cats.find((c: any) => c.name === 'Comida').id
  const month = (await apiGet(page, '/api/dashboard')).month
  for (let i = 0; i < 60; i++) await apiPost(page, '/api/transactions', { account_id: accounts[0].id, category_id: comida, amount_cents: 100, occurred_at: `${month}-01T12:00`, merchant: `Compra privada ${i}` })
  await page.goto('/movimientos')
  await page.getByLabel('Buscar', { exact: true }).fill('Compra privada')
  await page.getByLabel('Categoría', { exact: true }).selectOption(comida)
  await expect(page.locator('.tx')).toHaveCount(50)
  await page.getByRole('button', { name: 'Mostrar más' }).click()
  await expect(page.locator('.tx')).toHaveCount(60)
  expect(page.url()).not.toContain('privada')
  await page.locator('.tx').last().scrollIntoViewIfNeeded()
  await page.locator('.tx').last().click()
  await page.getByRole('dialog', { name: 'Editar gasto' }).getByRole('button', { name: 'Cerrar', exact: true }).click()
  await expect(page.locator('.tx').last()).toBeFocused()
  const y = await page.evaluate(() => window.scrollY)
  await page.locator('a[href="/plan"]:visible').first().click()
  await page.getByRole('button', { name: 'Mes anterior' }).click()
  const planUrl = page.url()
  await page.locator('a[href^="/movimientos"]:visible').first().click()
  await expect(page.getByLabel('Buscar', { exact: true })).toHaveValue('Compra privada')
  await expect(page.getByLabel('Categoría', { exact: true })).toHaveValue(comida)
  await expect(page.locator('.tx')).toHaveCount(60)
  // El enlace superior se pulsa tras desplazarse: restaurar la posición registrada sigue siendo posible.
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
  expect(y).toBeGreaterThan(0)
  await page.locator('a[href="/plan"]:visible').first().click()
  await expect(page).toHaveURL(planUrl)
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Movimientos', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Categoría', { exact: true })).toHaveValue(comida)
  await expect(page.getByLabel('Buscar', { exact: true })).toHaveValue('')
  await page.getByRole('button', { name: 'Limpiar filtros' }).click()
  await expect(page.getByLabel('Categoría', { exact: true })).toHaveValue('')
})

