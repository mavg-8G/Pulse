import { mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { apiGet, apiPost, expect, expectAccessible, register, test } from './helpers'

const output = fileURLToPath(new URL('../../artifacts/ui/', import.meta.url))

test('inicio aprovecha el espacio, permite pausar el pulso y muestra datos reales', async ({ page }, info) => {
  const desktop = info.project.name === 'escritorio'
  if (desktop) await page.setViewportSize({ width: 1920, height: 1080 })
  await register(page)
  await expect(page.locator('.dashboard')).toBeVisible()
  if (desktop) {
    const box = await page.locator('.dashboard-lead').boundingBox()
    expect(box!.width).toBeGreaterThan(1400)
    await page.getByRole('navigation', { name: 'Principal' }).getByRole('link', { name: 'Categorías', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Categorías', exact: true })).toBeVisible()
    await page.goto('/')
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(page.getByTestId('month-total')).toHaveText(/0,00/)
  await expect(page.locator('.page-content')).toHaveCSS('opacity', '1')
  await expect(page.locator('.dashboard')).toHaveCSS('opacity', '1')
  await expectAccessible(page, 'Inicio vacío')
  mkdirSync(output, { recursive: true })
  await page.screenshot({ path: `${output}inicio-vacio-${info.project.name}.png`, fullPage: true, animations: 'disabled' })

  await expect(page.getByRole('button', { name: /Pausar animaciones|Activar animaciones/ })).toHaveCount(0)
  await page.goto('/ajustes')
  await expect(page.locator('.page-content')).toHaveCSS('opacity', '1')
  await expectAccessible(page, 'Ajustes con control de animaciones')
  await page.screenshot({ path: `${output}ajustes-apariencia-${info.project.name}.png`, fullPage: true, animations: 'disabled' })
  const toggle = page.getByRole('button', { name: 'Pausar animaciones', exact: true })
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await toggle.click()
  await expect(page.locator('html')).toHaveAttribute('data-motion', 'paused')
  await expect(page.getByRole('button', { name: 'Activar animaciones', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.goto('/')
  await expect(page.locator('.dashboard-lead')).toBeVisible()
  expect(await page.locator('.dashboard-lead').evaluate((e) => getComputedStyle(e).animationName)).toBe('none')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-motion', 'paused')
  await page.goto('/ajustes')
  await page.getByRole('button', { name: 'Activar animaciones', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-motion', 'on')
  await page.goto('/')
  await expect(page.locator('.dashboard-lead')).toBeVisible()
  expect(await page.locator('.dashboard-lead').evaluate((e) => getComputedStyle(e).animationName)).not.toBe('none')

  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await page.locator('.dashboard-lead').evaluate((e) => getComputedStyle(e).animationName)).toBe('none')
  await page.emulateMedia({ reducedMotion: 'no-preference' })

  const cats = await apiGet(page, '/api/categories')
  const accounts = await apiGet(page, '/api/accounts')
  const comida = cats.find((c: { name: string }) => c.name === 'Comida')
  const transporte = cats.find((c: { name: string }) => c.name === 'Transporte')
  const local = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Guayaquil', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(new Date())
  const value = (part: string) => Number(local.find((p) => p.type === part)!.value)
  await apiPost(page, '/api/accounts', { name: 'Visa Pichincha', type: 'credit_card', institution: 'Banco Pichincha', card_suffix: '989' })
  await apiPost(page, '/api/budgets', { category_id: comida.id, amount_cents: 30000, thresholds: '50,80,100' })
  await apiPost(page, '/api/budgets', { category_id: transporte.id, amount_cents: 10000, thresholds: '50,80,100' })
  for (const [name, cents, category, daysAgo] of [['Supermaxi', 6840, comida.id, 0], ['Café de la mañana', 450, comida.id, 1], ['Uber', 820, transporte.id, 1], ['Almuerzo', 1450, comida.id, 3]] as const) {
    const date = new Date(Date.UTC(value('year'), value('month') - 1, Math.max(1, value('day') - daysAgo), 17))
    await apiPost(page, '/api/transactions', { account_id: accounts[0].id, category_id: category, amount_cents: cents, occurred_at: date.toISOString(), merchant: name })
  }
  await page.reload()
  await expect(page.getByTestId('month-total')).toHaveText(/95,60/)
  await expect(page.getByText('Supermaxi', { exact: true })).toBeVisible()
  await expect(page.getByRole('progressbar', { name: 'Porcentaje del presupuesto utilizado' })).toHaveAttribute('aria-valuenow', '23')
  await expect(page.locator('.page-content')).toHaveCSS('opacity', '1')
  await expect(page.locator('.dashboard')).toHaveCSS('opacity', '1')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expectAccessible(page, 'Inicio con gastos')
  await page.screenshot({ path: `${output}inicio-con-gastos-${info.project.name}.png`, fullPage: true, animations: 'disabled' })

  await page.goto('/ajustes')
  const themeSaved = page.waitForResponse((r) => r.url().endsWith('/api/me') && r.request().method() === 'PATCH')
  await page.getByRole('group', { name: 'Tema', exact: true }).getByRole('button', { name: 'Oscuro', exact: true }).click()
  expect((await themeSaved).ok()).toBe(true)
  await expect(page.getByRole('group', { name: 'Tema', exact: true }).getByRole('button', { name: 'Oscuro', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('.page-content')).toHaveCSS('opacity', '1')
  await expect(page.locator('.dashboard')).toHaveCSS('opacity', '1')
  await expectAccessible(page, 'Inicio oscuro')
  await page.screenshot({ path: `${output}inicio-oscuro-${info.project.name}.png`, fullPage: true, animations: 'disabled' })
})
